// ==================== npm package ====================
// The public @enaium/ffmpeg-kmp package ships the standalone Emscripten
// runtime, the wasm module and a small loader. Kotlin/JS and Kotlin/Wasm users
// keep the embedded klib path; plain JavaScript consumers instantiate the same
// runtime through initFFmpegKmp().
//
// npm only accepts three-component semver, so 9.0.2.1 becomes 9.0.2-1. The
// package is still published with the `latest` tag.
val npmPackageVersion: String by lazy {
    val parts = rootProject.version.toString().split('.')
    val base = parts.take(3).joinToString(".")
    val revision = parts.drop(3).joinToString(".")
    if (revision.isEmpty()) base else "$base-$revision"
}

val bridgeWebDir = rootProject.project(":ffmpeg-kmp:bridge")
    .layout.buildDirectory.dir("web").get().asFile
val webGlueSource = rootProject.file(
    "ffmpeg-kmp/bridge/src/webMain/kotlin/cn/enaium/ffmpeg/native/FFmpegWebGlue.kt",
)
val wasmNpmDir = layout.buildDirectory.dir("npm").get().asFile

tasks.register("assembleWasmNpm") {
    group = "build"
    description = "Stages the @enaium/ffmpeg-kmp npm package in build/npm."
    dependsOn(":ffmpeg-kmp:bridge:linkFFmpegWasm")
    inputs.file(webGlueSource)
    inputs.files(
        bridgeWebDir.resolve("ffmpeg_kmp.js"),
        bridgeWebDir.resolve("ffmpeg_kmp.wasm"),
    )
    inputs.property("npmPackageVersion", npmPackageVersion)
    outputs.dir(wasmNpmDir)
    doLast {
        wasmNpmDir.deleteRecursively()
        wasmNpmDir.mkdirs()
        bridgeWebDir.resolve("ffmpeg_kmp.js")
            .copyTo(wasmNpmDir.resolve("ffmpeg_kmp.js"), overwrite = true)
        bridgeWebDir.resolve("ffmpeg_kmp.wasm")
            .copyTo(wasmNpmDir.resolve("ffmpeg_kmp.wasm"), overwrite = true)
        rootProject.file("LICENSE").copyTo(wasmNpmDir.resolve("LICENSE"), overwrite = true)

        // Reuse the initializer that the Kotlin/JS and Kotlin/Wasm targets
        // eval, so there is only one runtime glue implementation.
        val glueText = webGlueSource.readText()
        val marker = "internal const val FFMPEG_WEB_GLUE_JS: String = \"\"\""
        val start = glueText.indexOf(marker)
        require(start >= 0) { "FFMPEG_WEB_GLUE_JS is missing from $webGlueSource" }
        val bodyStart = start + marker.length
        val bodyEnd = glueText.indexOf("\n\"\"\"", bodyStart)
        require(bodyEnd > bodyStart) { "FFMPEG_WEB_GLUE_JS is not closed in $webGlueSource" }
        val initializer = glueText.substring(bodyStart, bodyEnd).trim()
        require(initializer.startsWith("(runtimeBase64, wasmBase64")) {
            "unexpected FFMPEG_WEB_GLUE_JS shape"
        }

        wasmNpmDir.resolve("ffmpeg_kmp_glue.js").writeText(
            """
            // Generated by :ffmpeg-kmp:assembleWasmNpm from FFmpegWebGlue.kt. Do not edit.
            // Emscripten module loader for @enaium/ffmpeg-kmp.

            const initializeFFmpeg = $initializer;

            const isNode = typeof process !== 'undefined' &&
              process.versions != null && process.versions.node != null;

            const encodeBase64 = (bytes) => {
              if (typeof Buffer !== 'undefined') return Buffer.from(bytes).toString('base64');
              let text = '';
              const chunk = 0x8000;
              for (let i = 0; i < bytes.length; i += chunk) {
                text += String.fromCharCode.apply(null, bytes.subarray(i, i + chunk));
              }
              return btoa(text);
            };

            const loadBytes = async (source) => {
              if (source instanceof Uint8Array) return source;
              if (source instanceof ArrayBuffer) return new Uint8Array(source);
              if (isNode) {
                const { readFile } = await import('node:fs/promises');
                return new Uint8Array(await readFile(source));
              }
              const response = await fetch(source);
              if (!response.ok) {
                throw new Error('failed to load FFmpeg wasm asset: ' + response.status);
              }
              return new Uint8Array(await response.arrayBuffer());
            };

            /**
             * Instantiates the FFmpeg module and exposes its call helpers on
             * globalThis.__ffmpegWeb.
             *
             * @param {object|string|URL|Uint8Array|ArrayBuffer} [sources] optional
             *   `{ runtime, wasm }` locations or bytes. The default uses the
             *   ffmpeg_kmp.js and ffmpeg_kmp.wasm files shipped next to this module.
             * @returns {Promise<object>} the call helper table.
             */
            export async function initFFmpegKmp(sources = {}) {
              if (globalThis.__ffmpegWeb) return globalThis.__ffmpegWeb;
              if (sources instanceof Uint8Array || sources instanceof ArrayBuffer ||
                  typeof sources === 'string' || sources instanceof URL) {
                sources = { wasm: sources };
              }
              const runtimeSource = sources.runtime === undefined
                ? new URL('./ffmpeg_kmp.js', import.meta.url)
                : sources.runtime;
              const wasmSource = sources.wasm === undefined
                ? new URL('./ffmpeg_kmp.wasm', import.meta.url)
                : sources.wasm;
              const runtime = await loadBytes(runtimeSource);
              const wasm = await loadBytes(wasmSource);
              initializeFFmpeg(encodeBase64(runtime), encodeBase64(wasm));
              return globalThis.__ffmpegWeb;
            }

            export default initFFmpegKmp;
            """.trimIndent() + "\n",
        )

        wasmNpmDir.resolve("package.json").writeText(
            """
            {
              "name": "@enaium/ffmpeg-kmp",
              "version": "$npmPackageVersion",
              "description": "Emscripten-compiled FFmpeg module and JS glue for the ffmpeg-kmp wasmJs target",
              "license": "LGPL-2.1-or-later",
              "type": "module",
              "exports": {
                ".": "./ffmpeg_kmp_glue.js",
                "./ffmpeg_kmp.js": "./ffmpeg_kmp.js",
                "./ffmpeg_kmp.wasm": "./ffmpeg_kmp.wasm",
                "./package.json": "./package.json"
              },
              "files": ["ffmpeg_kmp_glue.js", "ffmpeg_kmp.js", "ffmpeg_kmp.wasm", "LICENSE"],
              "homepage": "https://github.com/Enaium/ffmpeg-kmp",
              "repository": {
                "type": "git",
                "url": "git+https://github.com/Enaium/ffmpeg-kmp.git"
              },
              "bugs": {
                "url": "https://github.com/Enaium/ffmpeg-kmp/issues"
              },
              "keywords": ["ffmpeg", "wasm", "webassembly", "video", "audio"]
            }
            """.trimIndent() + "\n",
        )
    }
}

tasks.register<Exec>("publishWasmNpm") {
    group = "publishing"
    description = "Publishes @enaium/ffmpeg-kmp to npm (token: npm.publish.key)."
    dependsOn("assembleWasmNpm")
    workingDir = wasmNpmDir
    val npmKey = providers.gradleProperty("npm.publish.key")
    doFirst {
        val key = npmKey.orNull?.takeIf { it.isNotBlank() }
            ?: throw GradleException(
                "npm.publish.key is not set: add it to ~/.gradle/gradle.properties " +
                    "or pass -Pnpm.publish.key=<token>",
            )
        // NODE_AUTH_TOKEN is expanded by npm from the environment, so the token
        // never lands in package.json or the tarball.
        environment("NODE_AUTH_TOKEN", key)
        wasmNpmDir.resolve(".npmrc").writeText(
            "//registry.npmjs.org/:_authToken=\${NODE_AUTH_TOKEN}\n",
        )
    }
    commandLine("npm", "publish", "--access", "public", "--tag", "latest")
}

